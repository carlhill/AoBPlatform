/**
 * THE HASH INPUT IS PINNED, AND THERE IS ONLY ONE OF IT.
 *
 * `canonicalJson` decides what an agreement's SHA-256 covers. Until 12 September
 * 2026 it was declared three times inside `apps/core/src/render` — in
 * `renderer.ts`, `agreement-document.ts` and privately in `pdf-renderer.ts` —
 * with none importing another. All three were character-for-character
 * equivalent, so nothing was ever wrong; the exposure was that a hash function
 * existing three times can diverge once, silently, and surface months later as
 * an old agreement that no longer verifies (hard rule 13: one deterministic
 * render path, two renders byte-identical).
 *
 * These tests do two jobs the refactor needs:
 *   1. pin the EXACT output, so the merge provably changed no digest and no
 *      future edit can change one by accident; and
 *   2. assert there is still exactly one implementation, so a fourth cannot
 *      quietly appear the next time somebody needs to hash something.
 */
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { canonicalJson } from './canonical-json';
import { canonicalJson as viaRenderer } from './renderer';
import { canonicalJson as viaDocument } from './agreement-document';

/**
 * Chosen to cover every branch and every rule the docstring claims: scalars,
 * nesting, array order, key sorting across cases and non-ASCII, escaping, and
 * the `undefined` wart that must be preserved.
 */
const CASES: ReadonlyArray<readonly [string, unknown]> = [
  ['null', null],
  ['string', 'x'],
  ['number', 42],
  ['boolean', true],
  ['nested objects and arrays', { b: 1, a: [3, { z: 1, y: 2 }] }],
  ['an undefined property', { u: undefined, n: null }],
  ['arrays keep their order', [1, [2, [3]]]],
  ['keys sort by code unit, not locale', { ä: 1, a: 2, Z: 3, '': 4 }],
  ['deep nesting', { nested: { deep: { deeper: [{ k: 'v' }] } } }],
  ['strings are escaped by JSON.stringify', { s: 'quote" and \\ and \n newline' }],
  ['an empty object and an empty array', { o: {}, a: [] }],
];

describe('canonical_json_keeps_its_exact_output', () => {
  /*
   * GOLDEN VALUES, WRITTEN OUT IN FULL rather than snapshotted. A snapshot file
   * can be regenerated by a tired person with `-u`; a literal in the test has to
   * be edited deliberately, which is the point when the digest of every future
   * agreement is on the line.
   */
  it.each([
    ['null', 'null'],
    ['string', '"x"'],
    ['number', '42'],
    ['boolean', 'true'],
    ['nested objects and arrays', '{"a":[3,{"y":2,"z":1}],"b":1}'],
    ['an undefined property', '{"n":null,"u":undefined}'],
    ['arrays keep their order', '[1,[2,[3]]]'],
    ['keys sort by code unit, not locale', '{"":4,"Z":3,"a":2,"ä":1}'],
    ['deep nesting', '{"nested":{"deep":{"deeper":[{"k":"v"}]}}}'],
    ['an empty object and an empty array', '{"a":[],"o":{}}'],
  ])('%s', (name, expected) => {
    const found = CASES.find(([label]) => label === name);
    expect(found).toBeDefined();
    expect(canonicalJson(found![1])).toBe(expected);
  });

  /**
   * THE WART, NAMED SO NOBODY "FIXES" IT. `undefined` is serialised literally,
   * which is not valid JSON. This output is hashed, never parsed, and every
   * agreement stored to date was hashed by a function that behaves this way.
   * Changing it would move the digest of every future render and break the
   * comparison against every past one; it would have to be a versioned renderer
   * change with the old behaviour kept for old artefacts.
   */
  it('serialises an undefined property literally, on purpose', () => {
    expect(canonicalJson({ u: undefined })).toBe('{"u":undefined}');
  });

  /** Two objects differing only in key order hash identically. That is the job. */
  it('is order-independent for objects and order-dependent for arrays', () => {
    const sha = (v: unknown) => createHash('sha256').update(canonicalJson(v), 'utf8').digest('hex');
    expect(sha({ x: 1, y: 2 })).toBe(sha({ y: 2, x: 1 }));
    expect(sha([1, 2])).not.toBe(sha([2, 1]));
  });
});

describe('the_render_path_has_exactly_one_canonical_json', () => {
  /**
   * A structural check, because an intention does not survive a busy afternoon
   * (wow.md §10). If somebody adds a fourth copy, this fails and names the file.
   */
  it('declares canonicalJson in exactly one file under src/render', () => {
    const dir = __dirname;
    const declaring = readdirSync(dir)
      .filter((f) => f.endsWith('.ts'))
      .filter((f) => /(?:^|\n)\s*(?:export\s+)?function canonicalJson\b/.test(readFileSync(join(dir, f), 'utf8')));
    expect(declaring).toEqual(['canonical-json.ts']);
  });

  /**
   * And the two modules that used to declare their own still export the name, so
   * the merge moved no import. `agreement-pdf-renderer` reaches it through
   * `agreement-document`.
   */
  it('is the same function however it is reached', () => {
    expect(viaRenderer).toBe(canonicalJson);
    expect(viaDocument).toBe(canonicalJson);
  });
});
