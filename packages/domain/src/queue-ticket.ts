/**
 * THE NUMBER ON THE CARD IN THE PATIENT'S HAND — `QUEUE-TICKETS.md`.
 *
 * Carl, 12 September 2026: *"some practices have a manual card system. The
 * patient on going to the practice, takes a card with a number and reception
 * will call the number when the number is next in the manual list."* A practice
 * with no patient-management feed is otherwise asked to match names on a screen
 * against faces in a room; the card number is how that room already works, and
 * the platform should speak it rather than replace it.
 *
 * THE ONE THING IT MUST NEVER BECOME (§2, hard rule 1, REQ-VER-02). **A ticket
 * is not an identity identifier and nothing may verify a patient by it.** The
 * approved set is name, date of birth, gender, address, patient record number
 * and IHI, and it is non-configurable — quietly adding a seventh is the most
 * likely design mistake in this whole regime. A card number is handed to the
 * wrong person, reused every day and left face up on a counter. Nothing in this
 * file is reachable from a verification path, and `normaliseQueueTicket` is
 * deliberately not a validator of anybody: it tidies a string, and that is all
 * it does.
 *
 * IT NEVER REACHES AN AGREEMENT. Not a particular, never rendered, no field on
 * the artefact — the s 65C data set is fixed and adding to a signed instrument
 * is the risk hard rule 4 exists to prevent.
 *
 * AND IT IS NOT THE RUNNING ORDER (§5a). The number is the PATIENT's handle —
 * what they are holding and what they will be called by — and the running order
 * is RECEPTION's, changed through the morning as walk-ins arrive. Number 14
 * being called before number 9 is an ordinary morning, not an error state.
 */

/**
 * WHERE A NUMBER CAME FROM, IN PRECEDENCE ORDER (Carl, 12 September 2026;
 * D-2026-09-12-18).
 *
 * `QUEUE-TICKETS.md` §3 used to read *"never generated by us"*. It is now
 * narrowed rather than abandoned, and the order below IS the rule:
 *
 *  1. `practice_card` — the practice's own card box, where they hand them out.
 *  2. `practice_software` — a number their PMS carried on the arrival.
 *  3. `allocated` — one this platform issued, because there was neither.
 *
 * WHY THAT IS NOT A CONTRADICTION. The worry behind the original wording was a
 * SECOND queue competing with the practice's own, and precedence is exactly
 * what protects it: where they have a card box we never invent a rival to it,
 * and where they have neither cards nor a feed there is no other queue, so ours
 * is the only handle the patient has rather than a competitor to anything.
 *
 * THE ORDER OF THIS ARRAY IS THE PRECEDENCE, so a reader cannot learn the rule
 * from one file and the order from another. The database CHECK
 * `arrivals_ticket_source_check` mirrors these three values.
 */
export const QUEUE_TICKET_SOURCES = ['practice_card', 'practice_software', 'allocated'] as const;

export type QueueTicketSource = (typeof QUEUE_TICKET_SOURCES)[number];

/** The longest a ticket may be. Past every card box anybody has described. */
export const QUEUE_TICKET_MAX_LENGTH = 8;

/**
 * A TICKET AS IT IS STORED — trimmed, upper-cased, and cut to length.
 *
 * A SHORT STRING AND NOT AN INTEGER, because practices use `A12` and `012` as
 * well as `12`, and `012` is not `12` to the person holding the card.
 *
 * UPPER-CASED so `a12` typed at the desk and `A12` printed on the card are one
 * number, which is what the duplicate warning has to compare.
 *
 * RETURNS NULL FOR NOTHING AT ALL, and null is a complete answer: a ticket is
 * optional always and no flow refuses to proceed for want of one (§5.1, hard
 * rule 8). A caller that gets null writes no ticket and no source, which is the
 * state the database insists the two share.
 *
 * IT NEVER GENERATES. Allocation lives on the server, where the practice and
 * the day are known; this only tidies what somebody supplied.
 */
export function normaliseQueueTicket(value: string | null | undefined): string | null {
  if (typeof value !== 'string') return null;
  const tidied = value.trim().toUpperCase().slice(0, QUEUE_TICKET_MAX_LENGTH);
  return tidied === '' ? null : tidied;
}

/**
 * THE NEXT NUMBER TO ALLOCATE, given what this practice has already issued
 * TODAY.
 *
 * PLAIN DIGITS, AND DELIBERATELY NOT PREFIXED. A practice reaching this branch
 * has no card box and no feed, so there is no house style to match and nothing
 * to be confused with; `1`, `2`, `3` is what a person would write on a pad.
 *
 * IT COUNTS ONLY WHAT WE ALLOCATED. A number that came off the practice's own
 * card box is theirs and says nothing about where our sequence has got to — and
 * a practice that switches its card box on mid-morning must not push our next
 * number to `A13`.
 *
 * A COLLISION IS A WARNING AND NEVER A REFUSAL (§5.3). Two receptionists
 * arriving two patients in the same instant can both read the same highest
 * number; the day then holds two number sevens, which is exactly what a card
 * box that wraps around does anyway, and the desk says so rather than
 * refusing anybody. There is no unique index for the same reason.
 */
export function nextAllocatedTicket(alreadyAllocatedToday: readonly string[]): string {
  let highest = 0;
  for (const ticket of alreadyAllocatedToday) {
    const asNumber = Number.parseInt(ticket, 10);
    if (Number.isFinite(asNumber) && asNumber > highest) highest = asNumber;
  }
  return String(highest + 1);
}
